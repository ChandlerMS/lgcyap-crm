import test from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdir, mkdtemp, writeFile, rm } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { JSDOM } from 'jsdom';
import { createElement as h, act } from 'react';
import { createRoot } from 'react-dom/client';
const require = createRequire(import.meta.url);
test('Email composes through the existing provider and compact Inbox retains refresh and collapse controls', async () => {
  await mkdir('work', { recursive: true }); const dir = await mkdtemp('work/dashboard-communications-');
  const dom = new JSDOM('<div id="app"></div>', { url: 'https://crm.example.test' });
  const previous = { window: globalThis.window, document: globalThis.document, fetch: globalThis.fetch };
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, IS_REACT_ACT_ENVIRONMENT: true });
  window.HTMLInputElement.prototype.attachEvent = function () {};
  window.HTMLInputElement.prototype.detachEvent = function () {};
  window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
  window.HTMLDialogElement.prototype.close = function () { this.open = false; };
  let root; const requests = [];
  try {
    await writeFile(`${dir}/entry.tsx`, `export {default as Email} from '../../app/recruit-email-panel'; export {RecruitEmailProvider} from '../../app/recruit-email'; export {default as Inbox} from '../../app/inbox-workspace'; export {default as HubSpotWorkspace} from '../../app/hubspot-workspace'; export {DashboardSection} from '../../app/dashboard-section';`);
    await build({ entryPoints: [`${dir}/entry.tsx`], outfile: `${dir}/bundle.cjs`, bundle: true, platform: 'node', format: 'cjs', external: ['react', 'react/*', 'react-dom', 'react-dom/*'], loader: { '.css': 'empty' }, logLevel: 'silent' });
    const { Email, RecruitEmailProvider, Inbox, DashboardSection, HubSpotWorkspace } = require(`${process.cwd()}/${dir}/bundle.cjs`);
    globalThis.fetch = async (url, options) => { if (url === '/api/email?connection=1') return Response.json({ canRead: false }); requests.push({ url, body: JSON.parse(options.body) }); if (url === '/api/recruit-email') return Response.json({ recipient: { name: 'Alex', email: 'alex@example.test' }, contactUrl: 'https://app.hubspot.com/contacts/50894788/contact/123', templates: [] }); return Response.json({ status: 'available', tool: 'inbox', records: [], complete: true, continuation: null }); };
    let refreshed = 0;
    root = createRoot(document.getElementById('app'));
    await act(async () => root.render(h(RecruitEmailProvider, { recruits: [{ id: '123', name: 'Alex', email: 'alex@example.test' }], disabled: false }, h(DashboardSection, { id: 'email', label: 'Email' }, h(Email, { recruits: [{ id: '123', name: 'Alex', email: 'alex@example.test' }, { id: 'demo', name: 'Test', email: 'test@example.test', isDemo: true }], onRefresh: () => refreshed++ })))));
    const button = text => [...document.querySelectorAll('button')].find(item => item.textContent === text || item.getAttribute('aria-label') === text);
    await act(async () => document.querySelector('[aria-label="Email view"] button:nth-child(2)').click());
    assert.match(document.querySelector('table').textContent, /alex@example.test/); assert.doesNotMatch(document.querySelector('table').textContent, /test@example.test/);
    await act(async () => button('Refresh').click()); assert.equal(refreshed, 1);
    await act(async () => button('New Email').click()); assert.equal(document.querySelector('dialog').open, true);
    assert.ok(button('Collapse Email'));
    assert.equal(document.querySelector('#today-email-title a').getAttribute('href'), '#email');
    const compose = button('New Email'); assert.ok(compose.classList.contains('summary-add'));
    assert.equal(compose.querySelector('[aria-hidden="true"]').textContent, '+');
    assert.equal(compose.nextElementSibling.getAttribute('aria-label'), 'Collapse Email');
    const emailNative = [...document.querySelectorAll('[data-section-heading] a')].find(link => link.textContent.startsWith('Open in HubSpot'));
    assert.ok(emailNative);
    assert.equal(emailNative.target, '_blank');
    assert.ok(emailNative.querySelector('svg'));
    assert.equal([...document.querySelectorAll('button')].filter(item => item.getAttribute('aria-label') === 'New Email').length, 1);
    assert.equal(document.querySelectorAll('[aria-label="Collapse Email"]').length, 1);
    await act(async () => button('Close email').click());
    const address = [...document.querySelectorAll('td button')].find(item => item.textContent === 'alex@example.test');
    assert.ok(address); await act(async () => address.click());
    assert.equal(document.querySelector('dialog').open, true);
    assert.equal(requests.at(-1).body.recruitId, '123');
    assert.ok(document.querySelector('td [aria-label="Call Alex with RingCentral"]'));
    assert.ok(document.querySelector('td [aria-label="Text Alex with RingCentral"]'));
    assert.doesNotMatch(document.querySelector('table').textContent, /Email Alex/);
    await act(async () => root.render(h(RecruitEmailProvider, { recruits: [], disabled: false }, h(DashboardSection, { id: 'inbox', label: 'Inbox' }, h(Inbox, { compact: true, pageHref: '#inbox', onUnauthorized() {} })))));
    await act(async () => { await new Promise(resolve => setTimeout(resolve, 30)); });
    assert.equal(document.querySelector('h1'), null); assert.equal(document.querySelector('h2 a').getAttribute('href'), '#inbox');
    assert.ok(document.querySelector('[data-section-heading]'));
    assert.ok(button('Collapse Inbox'));
    const newConversation = document.querySelector('a[aria-label="New message in HubSpot"]');
    assert.ok(newConversation.classList.contains('summary-add'));
    assert.equal(newConversation.querySelector('[aria-hidden="true"]').textContent, '+');
    assert.equal(document.querySelectorAll('[data-section-heading] .btn-primary').length, 0, 'there is no duplicate text compose button');
    const inboxNative = [...document.querySelectorAll('[data-section-heading] a')].find(link => link.textContent.startsWith('Open in HubSpot'));
    assert.ok(inboxNative.querySelector('svg'));
    assert.equal(inboxNative.className, emailNative.className);
    assert.equal(newConversation.href, 'https://app.hubspot.com/live-messages/50894788');
    assert.equal(newConversation.target, '_blank');
    const before = requests.length;
    await act(async () => button('Refresh').click()); assert.ok(requests.length > before);
    await act(async () => button('Collapse Inbox').click());
    assert.equal(document.querySelector('.dashboard-section').classList.contains('is-collapsed'), true);
    assert.ok(button('Refresh'), 'header remains mounted when collapsed');
    await act(async () => root.render(h(Email, { recruits: [], compact: false })));
    assert.ok(document.querySelector('h1#page-title'));
    assert.equal(document.querySelector('h1 a'), null);
    assert.equal(button('Collapse Email'), undefined);
    for (const tool of ['help-desk', 'tickets']) {
      await act(async () => root.render(h(DashboardSection, { id: tool, label: tool }, h(HubSpotWorkspace, { key: tool, tool, compact: true, onUnauthorized() {} }))));
      await act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); });
      const plus = button('New support ticket'); assert.ok(plus); assert.ok(plus.classList.contains('summary-add'));
      await act(async () => plus.click());
      assert.match(document.body.textContent, /New Support Ticket/i);
      assert.ok(document.querySelector('form'));
    }
  } finally {
    if (root) await act(async () => root.unmount()); Object.assign(globalThis, previous); delete globalThis.IS_REACT_ACT_ENVIRONMENT;
    dom.window.close(); await rm(dir, { recursive: true, force: true });
  }
});
