import test from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { JSDOM } from 'jsdom';
import { createElement, act } from 'react';
import { resolveWorkspaceRoute } from '../app/recruiting-navigation.mjs';
const require = createRequire(import.meta.url);

test('Inbox hover Open shows the correct conversation, preserves drafts across close, and sends only on an explicit click', async () => {
  await mkdir('work', { recursive: true }); const dir = await mkdtemp('work/inbox-hover-');
  const dom = new JSDOM('<div id="app"></div>', { url: 'https://crm.example.test' });
  const replacements = { window: dom.window, document: dom.window.document, HTMLElement: dom.window.HTMLElement, HTMLInputElement: dom.window.HTMLInputElement, Node: dom.window.Node, innerWidth: 1200, innerHeight: 900, ResizeObserver: class { observe() {} disconnect() {} }, requestAnimationFrame: callback => setTimeout(callback, 0), IS_REACT_ACT_ENVIRONMENT: true };
  const before = Object.fromEntries([...Object.keys(replacements), 'fetch'].map(key => [key, globalThis[key]]));
  Object.assign(globalThis, replacements);
  let root, sends = 0, releaseSend, failSend = false;
  const wait = () => new Promise(resolve => setTimeout(resolve, 30));
  try {
    const { createRoot } = require('react-dom/client');
    await build({ entryPoints: ['app/support-summary.tsx'], outfile: `${dir}/bundle.cjs`, bundle: true, platform: 'node', format: 'cjs', external: ['react', 'react/*', 'react-dom', 'react-dom/*'], loader: { '.css': 'empty' }, logLevel: 'silent' });
    const SupportSummary = require(`${process.cwd()}/${dir}/bundle.cjs`).default;
    globalThis.fetch = async (url, options) => {
      const input = JSON.parse(options.body);
      if (url === '/api/inbox-reply') {
        if (input.action === 'prepare') return Response.json({ threadId: input.threadId, contextToken: 'synthetic', senderLabel: 'agent@example.test', recipientLabel: 'customer@example.test', channelLabel: 'Email' });
        sends++;
        assert.equal(input.threadId, '101');
        assert.equal(Object.hasOwn(input, 'recipients'), false);
        if (failSend) throw new Error('network lost');
        return new Promise(resolve => { releaseSend = () => resolve(Response.json({ status: 'sent' })); });
      }
      if (input.threadId) return Response.json({ tool: 'inbox', status: 'available', archive: 'all', selectedThreadId: input.threadId, messages: [{ id: 'm1', text: 'Synthetic customer question', direction: 'Incoming', createdAt: '2026-11-19T15:00:00Z' }], complete: true, partial: false, continuation: null });
      return Response.json({ tool: 'inbox', status: 'available', records: [{ id: '101', title: 'Conversation 101', status: 'Open' }] });
    };
    root = createRoot(document.getElementById('app'));
    const render = live => root.render(createElement(SupportSummary, { tool: 'inbox', live, onUnauthorized() { assert.fail('Unexpected sign-out'); } }));
    await act(async () => { render(true); await wait(); });
    const cardLink = document.querySelector('.summary-card-list a');
    assert.equal(cardLink.getAttribute('href'), '#inbox/thread/101');
    assert.deepEqual(resolveWorkspaceRoute(cardLink.hash), { view: 'inbox', id: '101' });
    const heading = document.querySelector('.summary-chips-heading');
    const hover = async () => { await act(async () => { heading.dispatchEvent(new dom.window.MouseEvent('mouseover', { bubbles: true, relatedTarget: document.body })); await wait(); }); };
    await hover();
    const panel = document.getElementById('inbox-summary-preview');
    const openButton = [...panel.querySelectorAll('button')].find(button => button.textContent.startsWith('Open conversation'));
    assert.ok(openButton);
    await act(async () => { openButton.click(); await wait(); });
    await act(wait);
    assert.match(panel.textContent, /Synthetic customer question/);
    assert.equal(panel.querySelector('a[href="#inbox/thread/101"]').textContent, 'Open full Inbox');
    let textarea = panel.querySelector('textarea');
    const type = async text => { await act(async () => { Object.getOwnPropertyDescriptor(dom.window.HTMLTextAreaElement.prototype, 'value').set.call(textarea, text); textarea.dispatchEvent(new dom.window.Event('input', { bubbles: true })); }); };
    await type('Thanks for the question.');
    assert.equal(sends, 0);
    await act(async () => { textarea.focus(); panel.dispatchEvent(new dom.window.MouseEvent('mouseout', { bubbles: true, relatedTarget: document.body })); await new Promise(resolve => setTimeout(resolve, 250)); });
    assert.equal(panel.hidden, false);
    await act(async () => [...panel.querySelectorAll('button')].find(button => button.textContent === 'Close preview').click());
    assert.equal(panel.hidden, true);
    await hover();
    assert.equal(panel.querySelector('textarea').value, 'Thanks for the question.');
    await act(async () => { textarea.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true })); });
    assert.equal(panel.hidden, true, 'Escape does not immediately reopen from restored heading focus');
    await hover();
    const send = () => [...panel.querySelectorAll('button')].find(button => button.textContent === 'Send reply');
    assert.equal(send().disabled, false);
    await act(async () => { send().click(); send().click(); await wait(); });
    assert.equal(sends, 1);
    assert.equal(textarea.value, 'Thanks for the question.');
    await act(async () => { releaseSend(); await wait(); });
    assert.equal(textarea.value, '');
    assert.match(panel.textContent, /Reply accepted by HubSpot/);
    failSend = true;
    await type('Second reply draft');
    await act(async () => { send().click(); await wait(); });
    assert.equal(sends, 2);
    assert.match(panel.textContent, /send outcome is uncertain/);
    assert.equal(send().disabled, true);
    await act(async () => [...panel.querySelectorAll('button')].find(button => button.textContent === '← Conversations').click());
    await act(async () => { [...panel.querySelectorAll('button')].find(button => button.textContent.startsWith('Open conversation')).click(); await wait(); });
    textarea = panel.querySelector('textarea');
    assert.equal(textarea.value, 'Second reply draft');
    assert.equal(send().disabled, true, 'switching back to a thread cannot unlock an uncertain send');
    await act(async () => { render(false); await wait(); });
    assert.equal(panel.querySelector('textarea'), null, 'demo mode must not retain the live composer');
    await act(async () => { render(true); await wait(); });
    assert.equal(panel.querySelector('textarea').value, 'Second reply draft');
    assert.equal(send().disabled, true);
    assert.equal(sends, 2, 'mode changes must never send a reply');
  } finally {
    if (root) await act(async () => root.unmount());
    Object.assign(globalThis, before); dom.window.close(); await rm(dir, { recursive: true, force: true });
  }
});
