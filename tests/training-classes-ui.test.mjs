import test from 'node:test';
import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { mkdir, mkdtemp, rm } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { JSDOM } from 'jsdom';
import { createElement, act } from 'react';
import { createRoot } from 'react-dom/client';
const require = createRequire(import.meta.url);
test('schedule supports upcoming/past, editor forms, failed saves, edits and confirmed cancellation', async () => {
  await mkdir('work', { recursive: true }); const dir = await mkdtemp('work/training-ui-');
  const dom = new JSDOM('<div id="app"></div>', { url: 'https://crm.example.test' });
  const old = { window: globalThis.window, document: globalThis.document, fetch: globalThis.fetch };
  Object.assign(globalThis, { window: dom.window, document: dom.window.document, IS_REACT_ACT_ENVIRONMENT: true });
  let root;
  const upcoming = { id: 'd261faed-f97c-45eb-86fb-c083aa23dc72', name: 'Agent fundamentals', startAt: '2099-12-01T14:00:00.000Z', endAt: '2099-12-01T16:00:00.000Z', trainer: 'Sarah', location: 'Online', meetingUrl: '', notes: '', status: 'scheduled', version: 1 };
  const past = { ...upcoming, id: 'aa61faed-f97c-45eb-86fb-c083aa23dc72', name: 'Past training', startAt: '2020-01-01T14:00:00.000Z', endAt: '2020-01-01T16:00:00.000Z' };
  let rows = [upcoming, past], canManage = false, fail = false, malformed = false, conflict = false; let finishRead = null; const writes = [];
  try {
    await build({ entryPoints: ['app/training-classes-page.tsx'], outfile: `${dir}/bundle.cjs`, bundle: true, platform: 'node', format: 'cjs', external: ['react', 'react/*', 'react-dom', 'react-dom/*'], loader: { '.css': 'empty' }, logLevel: 'silent' });
    const Page = require(`${process.cwd()}/${dir}/bundle.cjs`).default;
    globalThis.fetch = async (_url, options = {}) => {
      if (options.method !== 'POST') { if (finishRead) return new Promise(resolve => { finishRead.resolve = () => resolve(Response.json({ classes: rows, canManage })); }); return Response.json({ classes: rows, canManage }); }
      const input = JSON.parse(options.body); writes.push(input);
      if (malformed) return Response.json({});
      if (conflict) return Response.json({ error: 'This class changed. Refresh before editing.' }, { status: 409 });
      if (fail) return Response.json({ error: 'Fix the class details.' }, { status: 400 });
      const value = input.action === 'cancel' ? { ...rows.find(row => row.id === input.id), status: 'canceled', version: input.version + 1 } : { ...input, id: input.id ?? 'bb61faed-f97c-45eb-86fb-c083aa23dc72', version: (input.version ?? 0) + 1, status: 'scheduled' };
      rows = [...rows.filter(row => row.id !== value.id), value]; return Response.json({ class: value });
    };
    const click = async text => { const button = [...document.querySelectorAll('button')].find(item => item.textContent === text || item.getAttribute('aria-label') === text); assert.ok(button, text); await act(async () => button.click()); };
    const render = async () => { root = createRoot(document.getElementById('app')); await act(async () => root.render(createElement(Page))); await act(async () => { await new Promise(resolve => setTimeout(resolve, 20)); }); };
    await render();
    assert.match(document.body.textContent, /Agent fundamentals/); assert.doesNotMatch(document.body.textContent, /Past training/);
    assert.equal([...document.querySelectorAll('button')].some(button => button.textContent === 'Add class'), false);
    await click('Past'); assert.match(document.body.textContent, /Past training/);
    await act(async () => root.unmount()); canManage = true; await render();
    await click('Add class');
    const form = document.querySelector('form');
    const unload = new window.Event('beforeunload', { cancelable: true });
    window.dispatchEvent(unload); assert.equal(unload.defaultPrevented, true);
    // Native setters produce the input events React consumes in a DOM environment.
    const set = async (name, value) => { const field = form.elements.namedItem(name); await act(async () => { Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value').set.call(field, value); field.dispatchEvent(new window.Event('input', { bubbles: true })); field.dispatchEvent(new window.Event('change', { bubbles: true })); }); };
    await set('name', 'New training'); await set('start', '2099-12-02T09:00'); await set('end', '2099-12-02T10:00');
    fail = true;
    await act(async () => form.dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
    assert.match(document.body.textContent, /Fix the class details/); assert.equal(document.querySelector('[name="name"]').value, 'New training');
    fail = false;
    await act(async () => form.dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
    assert.ok(writes.at(-1).createId);
    assert.equal(writes[0].createId, writes[1].createId);
    assert.equal(writes.at(-1).startAt, '2099-12-02T14:00:00.000Z'); assert.equal(document.querySelector('form'), null);
    assert.match(document.body.textContent, /New training/);
    await click('Edit New training');
    assert.equal(document.querySelector('[name="start"]').value, '2099-12-02T09:00');
    await act(async () => document.querySelector('form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
    assert.equal(writes.at(-1).version, 1);
    await click('Cancel New training'); assert.equal(writes.at(-1).action, 'save');
    await click('Confirm cancellation');
    assert.equal(writes.at(-1).action, 'cancel'); assert.match(document.body.textContent, /Canceled/);
    await click('Edit Agent fundamentals');
    finishRead = {};
    await click('Refresh schedule');
    assert.equal(document.querySelector('button[type="submit"]').disabled, true);
    const previousWrites = writes.length;
    await act(async () => document.querySelector('form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
    assert.equal(writes.length, previousWrites);
    await act(async () => finishRead.resolve()); finishRead = null;
    conflict = true;
    await act(async () => document.querySelector('form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
    assert.match(document.body.textContent, /This class changed/);
    rows = rows.map(row => row.id === upcoming.id ? { ...row, name: 'Updated by another editor', version: 2 } : row);
    await click('Review latest class');
    assert.equal(document.querySelector('[name="name"]').value, 'Agent fundamentals');
    assert.match(document.querySelector('[aria-label="Latest saved class"]').textContent, /Updated by another editor/);
    await click('Use latest version for these edits');
    conflict = false; malformed = true;
    await act(async () => document.querySelector('form').dispatchEvent(new window.Event('submit', { bubbles: true, cancelable: true })));
    assert.equal(writes.at(-1).version, 2);
    assert.equal(document.querySelector('button[type="submit"]').disabled, true);
    assert.match(document.body.textContent, /could not be confirmed/);
    await click('Discard changes');
    assert.equal([...document.querySelectorAll('button')].find(button => button.textContent === 'Add class').disabled, true);
    assert.match(document.body.textContent, /Refresh the schedule to resolve/);
    malformed = false; await click('Refresh schedule');
    assert.equal([...document.querySelectorAll('button')].find(button => button.textContent === 'Add class').disabled, false);
  } finally {
    if (root) await act(async () => root.unmount()); Object.assign(globalThis, old); delete globalThis.IS_REACT_ACT_ENVIRONMENT;
    dom.window.close(); await rm(dir, { recursive: true, force: true });
  }
});
